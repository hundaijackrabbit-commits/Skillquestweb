CREATE OR REPLACE FUNCTION public.sync_profile_saved_skills()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  target_user UUID;
BEGIN
  IF TG_OP = 'DELETE' THEN
    target_user := OLD.user_id;
  ELSE
    target_user := NEW.user_id;
  END IF;

  UPDATE public.profiles
  SET saved_skills = COALESCE(
    (SELECT array_agg(s.skill_slug ORDER BY s.created_at) FROM public.saved_skills s WHERE s.user_id = target_user),
    '{}'::TEXT[]
  )
  WHERE id = target_user;

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS sync_profile_saved_skills_after_change ON public.saved_skills;
CREATE TRIGGER sync_profile_saved_skills_after_change
  AFTER INSERT OR DELETE ON public.saved_skills
  FOR EACH ROW EXECUTE FUNCTION public.sync_profile_saved_skills();

