-- Canonical saved-skill relation used by the current dashboard/save button.
-- A compatibility trigger keeps profiles.saved_skills in sync for older code paths.
CREATE TABLE IF NOT EXISTS public.saved_skills (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  skill_slug TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(user_id, skill_slug)
);

-- Preserve any skills that were previously stored only in profiles.saved_skills.
INSERT INTO public.saved_skills (user_id, skill_slug)
SELECT p.id, skill_slug
FROM public.profiles p
CROSS JOIN LATERAL unnest(COALESCE(p.saved_skills, '{}'::TEXT[])) AS skill_slug
ON CONFLICT (user_id, skill_slug) DO NOTHING;

ALTER TABLE public.saved_skills ENABLE ROW LEVEL SECURITY;

