CREATE OR REPLACE FUNCTION public.subscribe_newsletter(p_email TEXT, p_source TEXT DEFAULT 'website')
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF p_email IS NULL OR length(trim(p_email)) > 254 OR trim(p_email) !~* '^[^@\s]+@[^@\s]+\.[^@\s]+$' THEN
    RAISE EXCEPTION 'invalid email';
  END IF;

  INSERT INTO public.newsletter_subscribers (email, source, status)
  VALUES (lower(trim(p_email)), left(COALESCE(NULLIF(trim(p_source), ''), 'website'), 80), 'subscribed')
  ON CONFLICT (email) DO UPDATE
    SET status = 'subscribed',
        source = EXCLUDED.source,
        updated_at = NOW();
END;
$$;

GRANT EXECUTE ON FUNCTION public.subscribe_newsletter(TEXT, TEXT) TO anon, authenticated;

