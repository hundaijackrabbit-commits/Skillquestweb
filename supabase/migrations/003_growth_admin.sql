-- Public aggregate only: exposes popularity counts without exposing raw visitor events.
CREATE OR REPLACE FUNCTION public.get_trending_skills(p_days INTEGER DEFAULT 7, p_limit INTEGER DEFAULT 6)
RETURNS TABLE(item_slug TEXT, views BIGINT)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT e.item_slug, COUNT(*)::BIGINT AS views
  FROM public.content_events e
  WHERE e.event_type = 'skill_view'
    AND e.item_slug IS NOT NULL
    AND e.created_at >= NOW() - make_interval(days => LEAST(GREATEST(p_days, 1), 90))
  GROUP BY e.item_slug
  ORDER BY views DESC, e.item_slug ASC
  LIMIT LEAST(GREATEST(p_limit, 1), 50);
$$;

GRANT EXECUTE ON FUNCTION public.get_trending_skills(INTEGER, INTEGER) TO anon, authenticated;

